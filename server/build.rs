//! Packs every structure in `assets/structures` into the server, so a deploy
//! can't leave them behind. Each is checked here first: a structure naming a
//! block that isn't in `assets/blocks.ron` fails the build, with the file and
//! the name in the message, instead of showing up when the world generates.
//!
//! Writes `structures.rs` to OUT_DIR: a list of (file name, file text), read by
//! `src/world/generation/structures.rs`.

use std::{collections::HashSet, env, fs, path::PathBuf};

use serde::Deserialize;

/// Relative to this crate, which lives in the game repo next to assets/
const STRUCTURES: &str = "../assets/structures";
const BLOCKS: &str = "../assets/blocks.ron";

/// The one field of a blocks.ron entry this needs
#[derive(Deserialize)]
struct BlockEntry {
    name: String,
}

/// The one field of a structure file this checks (protocol's
/// `world::structure` reads the whole thing)
#[derive(Deserialize)]
struct StructureEntry {
    palette: Vec<String>,
}

fn main() {
    println!("cargo::rerun-if-changed={STRUCTURES}");
    println!("cargo::rerun-if-changed={BLOCKS}");

    let blocks = fs::read_to_string(BLOCKS).unwrap_or_else(|e| panic!("can't read {BLOCKS}: {e}"));
    let blocks: Vec<BlockEntry> =
        ron::from_str(&blocks).unwrap_or_else(|e| panic!("{BLOCKS} isn't valid: {e}"));
    let names: HashSet<&str> = blocks
        .iter()
        .map(|block| block.name.as_str())
        .chain(["air"])
        .collect();

    let mut files: Vec<PathBuf> = fs::read_dir(STRUCTURES)
        .unwrap_or_else(|e| panic!("can't read {STRUCTURES}: {e}"))
        .map(|entry| entry.expect("readable directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "ron"))
        .collect();
    // sorted so the same files always build the same list
    files.sort();

    let mut entries = String::new();
    for path in &files {
        let name = path.file_stem().unwrap().to_string_lossy();
        let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("can't read {path:?}: {e}"));
        let structure: StructureEntry =
            ron::from_str(&text).unwrap_or_else(|e| panic!("{path:?} isn't a valid structure: {e}"));
        for block in &structure.palette {
            assert!(
                names.contains(block.as_str()),
                "{path:?} uses block {block:?}, which isn't in {BLOCKS}"
            );
        }
        let absolute = fs::canonicalize(path).unwrap();
        entries += &format!("    ({name:?}, include_str!({:?})),\n", absolute.display().to_string());
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(
        out.join("structures.rs"),
        format!(
            "// Generated by server/build.rs from assets/structures. Don't edit.\n\
             /// Every structure file: (name, text)\n\
             pub const FILES: &[(&str, &str)] = &[\n{entries}];\n"
        ),
    )
    .unwrap();
}
