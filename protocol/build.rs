//! Reads the block list, `assets/blocks.ron`, and generates the `Block` constants
//! and property table that `src/world/block.rs` includes. Then the item list,
//! `assets/items.ron`, for `src/inventory/item.rs`: every block is an item too,
//! followed by the items that aren't blocks. Mistakes in either file (bad names,
//! duplicates, missing textures) fail the build here, with the name in the
//! message, instead of showing up in game.

use std::{collections::HashSet, env, fs, path::PathBuf};

use serde::Deserialize;

/// Relative to this crate. The protocol crate lives in the game repo, next to assets/
const BLOCKS: &str = "../assets/blocks.ron";
const ITEMS: &str = "../assets/items.ron";
const TEXTURES: &str = "../assets/images/blocks";

/// One entry of blocks.ron. Missing fields take the defaults below
#[derive(Deserialize)]
struct BlockEntry {
    name: String,
    /// None: solid unless it's a fluid
    solid: Option<bool>,
    #[serde(default)]
    fluid: bool,
    #[serde(default)]
    see_through: bool,
    #[serde(default)]
    textures: Textures,
}

/// One entry of items.ron
#[derive(Deserialize)]
struct ItemEntry {
    name: String,
    #[serde(default = "default_stack")]
    stack: u32,
    icon: Option<String>,
}

/// Items per inventory slot, unless an item says otherwise
fn default_stack() -> u32 {
    64
}

/// Lowercase letters, digits and _: usable as a file name and a constant name
fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

#[derive(Deserialize, Default)]
struct Textures {
    top: Option<String>,
    side: Option<String>,
    bottom: Option<String>,
}

fn main() {
    println!("cargo::rerun-if-changed={BLOCKS}");
    println!("cargo::rerun-if-changed={ITEMS}");
    println!("cargo::rerun-if-changed={TEXTURES}");

    let text = fs::read_to_string(BLOCKS).unwrap_or_else(|e| panic!("can't read {BLOCKS}: {e}"));
    let entries: Vec<BlockEntry> =
        ron::from_str(&text).unwrap_or_else(|e| panic!("{BLOCKS} isn't valid: {e}"));

    let mut seen = HashSet::new();
    // air is always id 0: not solid, never drawn, so it has no textures
    let mut consts = String::from("    pub const AIR: Block = Block(0);\n");
    let mut defs = String::from(
        "    BlockDef { name: \"air\", solid: false, fluid: false, see_through: false, top:\"\", side: \"\", bottom: \"\" },\n",
    );
    for (i, entry) in entries.iter().enumerate() {
        let name = &entry.name;
        let id = i + 1;
        assert!(
            valid_name(name),
            "{BLOCKS}: block {name:?} must be lowercase letters, digits and _"
        );
        assert!(name != "air", "{BLOCKS}: air is built in, remove it from the list");
        assert!(seen.insert(name.clone()), "{BLOCKS}: {name} is listed twice");
        // fluids are never solid: players move through them and see through them
        let solid = entry.solid.unwrap_or(!entry.fluid);
        assert!(!(solid && entry.fluid), "{BLOCKS}: {name} can't be both solid and a fluid");
        assert!(
            solid || !entry.see_through,
            "{BLOCKS}: {name} is see_through, which is for solid blocks (fluids are see-through already)"
        );

        // each face: the named texture, or the block's own name
        let face = |texture: &Option<String>| {
            let texture = texture.as_deref().unwrap_or(name);
            let file = format!("{TEXTURES}/{texture}.png");
            assert!(
                fs::exists(&file).unwrap_or(false),
                "{BLOCKS}: {name} uses texture {texture:?}, but {file} doesn't exist"
            );
            texture.to_owned()
        };
        let (top, side, bottom) = (
            face(&entry.textures.top),
            face(&entry.textures.side),
            face(&entry.textures.bottom),
        );

        consts += &format!("    pub const {}: Block = Block({id});\n", name.to_uppercase());
        defs += &format!(
            "    BlockDef {{ name: {name:?}, solid: {solid}, fluid: {}, see_through: {}, top: {top:?}, side: {side:?}, bottom: {bottom:?} }},\n",
            entry.fluid, entry.see_through
        );
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(
        out.join("blocks.rs"),
        format!(
            "// Generated by protocol/build.rs from assets/blocks.ron. Don't edit.\n\
             impl Block {{\n{consts}}}\n\n\
             /// Every block's properties, indexed by id\n\
             const DEFS: &[BlockDef] = &[\n{defs}];\n"
        ),
    )
    .unwrap();

    // ---- items: every block (not air), then items.ron's
    let text = fs::read_to_string(ITEMS).unwrap_or_else(|e| panic!("can't read {ITEMS}: {e}"));
    let items: Vec<ItemEntry> =
        ron::from_str(&text).unwrap_or_else(|e| panic!("{ITEMS} isn't valid: {e}"));
    let mut item_consts = String::new();
    let mut item_defs = String::new();
    for (id, entry) in entries.iter().enumerate() {
        let name = &entry.name;
        // a block's icon is its side texture
        let icon = entry.textures.side.as_deref().unwrap_or(name);
        item_consts += &format!("    pub const {}: Item = Item({id});\n", name.to_uppercase());
        item_defs += &format!(
            "    ItemDef {{ name: {name:?}, stack: {}, icon: {icon:?}, places: Some(Block::{}) }},\n",
            default_stack(),
            name.to_uppercase()
        );
    }
    for (i, item) in items.iter().enumerate() {
        let name = &item.name;
        let id = entries.len() + i;
        assert!(
            valid_name(name),
            "{ITEMS}: item {name:?} must be lowercase letters, digits and _"
        );
        assert!(
            seen.insert(name.clone()),
            "{ITEMS}: {name} is listed twice, or is already a block"
        );
        assert!(item.stack >= 1, "{ITEMS}: {name}'s stack must be at least 1");
        let icon = item.icon.as_deref().unwrap_or(name);
        let file = format!("{TEXTURES}/{icon}.png");
        assert!(
            fs::exists(&file).unwrap_or(false),
            "{ITEMS}: {name} uses icon {icon:?}, but {file} doesn't exist"
        );
        item_consts += &format!("    pub const {}: Item = Item({id});\n", name.to_uppercase());
        item_defs += &format!(
            "    ItemDef {{ name: {name:?}, stack: {}, icon: {icon:?}, places: None }},\n",
            item.stack
        );
    }
    fs::write(
        out.join("items.rs"),
        format!(
            "// Generated by protocol/build.rs from assets/blocks.ron and assets/items.ron.\n\
             // Don't edit.\n\
             impl Item {{\n{item_consts}}}\n\n\
             /// Every item's properties, indexed by id\n\
             const ITEM_DEFS: &[ItemDef] = &[\n{item_defs}];\n"
        ),
    )
    .unwrap();
}
