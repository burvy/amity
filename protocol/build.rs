//! Reads the block list, `assets/blocks.ron`, and generates the `Block` constants
//! and property table that `src/world/block.rs` includes. Mistakes in the file
//! (bad names, duplicates, missing textures) fail the build here, with the
//! block's name in the message, instead of showing up in game.

use std::{collections::HashSet, env, fs, path::PathBuf};

use serde::Deserialize;

/// Relative to this crate. The protocol crate lives in the game repo, next to assets/
const BLOCKS: &str = "../assets/blocks.ron";
const TEXTURES: &str = "../assets/images/blocks";

/// One entry of blocks.ron. Missing fields take the defaults below
#[derive(Deserialize)]
struct BlockEntry {
    name: String,
    #[serde(default = "yes")]
    solid: bool,
    #[serde(default)]
    textures: Textures,
}

#[derive(Deserialize, Default)]
struct Textures {
    top: Option<String>,
    side: Option<String>,
    bottom: Option<String>,
}

fn yes() -> bool {
    true
}

fn main() {
    println!("cargo::rerun-if-changed={BLOCKS}");
    println!("cargo::rerun-if-changed={TEXTURES}");

    let text = fs::read_to_string(BLOCKS).unwrap_or_else(|e| panic!("can't read {BLOCKS}: {e}"));
    let entries: Vec<BlockEntry> =
        ron::from_str(&text).unwrap_or_else(|e| panic!("{BLOCKS} isn't valid: {e}"));

    let mut seen = HashSet::new();
    // air is always id 0: not solid, never drawn, so it has no textures
    let mut consts = String::from("    pub const AIR: Block = Block(0);\n");
    let mut defs = String::from(
        "    BlockDef { name: \"air\", solid: false, top: \"\", side: \"\", bottom: \"\" },\n",
    );
    for (i, entry) in entries.iter().enumerate() {
        let name = &entry.name;
        let id = i + 1;
        assert!(
            !name.is_empty()
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "{BLOCKS}: block {name:?} must be lowercase letters, digits and _"
        );
        assert!(name != "air", "{BLOCKS}: air is built in, remove it from the list");
        assert!(seen.insert(name.clone()), "{BLOCKS}: {name} is listed twice");

        // each face: the named texture, or the block's own name
        let face = |texture: &Option<String>| {
            let texture = texture.as_deref().unwrap_or(name);
            let file = format!("{TEXTURES}/{texture}.png");
            assert!(
                fs::exists(&file).unwrap_or(false),
                "{BLOCKS}: {name} uses texture {texture:?}, but {file} doesn't exist"
            );
            texture.to_owned()
        };
        let (top, side, bottom) = (
            face(&entry.textures.top),
            face(&entry.textures.side),
            face(&entry.textures.bottom),
        );

        consts += &format!("    pub const {}: Block = Block({id});\n", name.to_uppercase());
        defs += &format!(
            "    BlockDef {{ name: {name:?}, solid: {}, top: {top:?}, side: {side:?}, bottom: {bottom:?} }},\n",
            entry.solid
        );
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(
        out.join("blocks.rs"),
        format!(
            "// Generated by protocol/build.rs from assets/blocks.ron. Don't edit.\n\
             impl Block {{\n{consts}}}\n\n\
             /// Every block's properties, indexed by id\n\
             const DEFS: &[BlockDef] = &[\n{defs}];\n"
        ),
    )
    .unwrap();
}
